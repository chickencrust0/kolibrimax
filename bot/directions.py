"""
bot/directions.py — каталог направлений школы и подбор по возрасту.

Вынесено отдельным модулем, а не зашито в хендлер: список направлений и
возрастные рамки меняются от сезона к сезону, и править их должно быть
можно в одном месте, не трогая логику диалога.

Возрастные группы взяты из требований школы:
    3–4 года   — развивающий курс
    5 лет      — английский, робототехника, шахматы, подготовка к школе
    6–7 лет    — то же + изо
    8–13 лет   — английский, робототехника, шахматы, изо, китайский,
                 программирование
    6–11 лет   — дополнительно продлёнка «Академия полного дня»
"""

from typing import Dict, List

import settings

# code -> подпись кнопки. Коды короткие: они уезжают в payload
# callback-кнопки MAX, а он ограничен по длине.
DIRECTIONS: Dict[str, str] = {
    "dev": "🎨 Развивающий курс",
    "eng": "🇬🇧 Английский язык",
    "chi": "🇨🇳 Китайский язык",
    "rob": "🤖 Робототехника (LEGO WeDo 2)",
    "prog": "💻 Программирование",
    "chess": "♟️ Шахматы",
    "prep": "📚 Подготовка к школе",
    "art": "🖌️ Изо",
    "fullday": "🏫 Академия полного дня (продлёнка)",
}

# Короткие пояснения — чтобы родитель понимал, что за кнопкой, до звонка.
DESCRIPTIONS: Dict[str, str] = {
    "dev": "мягкая адаптация, моторика и речь, арт-терапия",
    "eng": "с погружением в языковую среду",
    "chi": "для самых любознательных",
    "rob": "конструирование и первые механизмы",
    "prog": "создание игр и сайтов с нуля",
    "chess": "логика, стратегия, умение принимать решения",
    "prep": "чтение, письмо и математика без стресса",
    "art": "рисование, лепка, творчество",
    "fullday": "присмотр, уроки и занятия во второй половине дня",
}


def directions_for_age(age: int) -> List[str]:
    """Коды направлений, подходящих ребёнку указанного возраста."""
    codes: List[str] = []

    if 3 <= age <= 4:
        codes = ["dev"]
    elif age == 5:
        codes = ["eng", "rob", "chess", "prep"]
    elif 6 <= age <= 7:
        codes = ["eng", "rob", "chess", "prep", "art"]
    elif 8 <= age <= 13:
        codes = ["eng", "rob", "chess", "art", "chi", "prog"]
    elif 14 <= age <= settings.MAX_AGE:
        # Для подростков отдельной сетки нет — предлагаем старшую группу,
        # менеджер уточнит при звонке. Лучше показать что-то осмысленное,
        # чем пустой экран.
        codes = ["eng", "chess", "art", "chi", "prog"]

    if 6 <= age <= 11:
        codes = codes + ["fullday"]

    return codes


def directions_for_ages(ages: List[int]) -> List[str]:
    """
    Объединение направлений для нескольких детей, БЕЗ дублей и с
    сохранением порядка каталога — иначе кнопки прыгали бы между
    показами и по ним было бы неудобно попадать.
    """
    matched = set()
    for age in ages:
        matched.update(directions_for_age(age))
    return [code for code in DIRECTIONS if code in matched]


def label(code: str) -> str:
    return DIRECTIONS.get(code, code)


def describe(code: str) -> str:
    text = DESCRIPTIONS.get(code)
    return f"{label(code)} — {text}" if text else label(code)


# Разумный потолок числа детей в одной заявке. Больше — почти наверняка
# человек прислал не возрасты, а что-то другое (год, номер, дату).
MAX_CHILDREN = 6


def parse_ages(text: str) -> List[int]:
    """
    Возраст детей из свободного текста: «7», «5 8», «5, 8», «5 и 8 лет».

    Повторы НЕ убираются: «5 5» — это двойняшки, и направления им нужно
    выбирать по отдельности. Раньше здесь стоял отсев дублей, и второй
    ребёнок из заявки просто пропадал.

    Числа вне разумных рамок (0 или больше 100) отбрасываются: это почти
    наверняка год рождения или номер телефона, а не возраст.
    """
    digits: List[int] = []
    current = ""
    for char in (text or ""):
        if char.isdigit():
            current += char
        else:
            if current:
                digits.append(int(current))
                current = ""
    if current:
        digits.append(int(current))

    result = [value for value in digits if 0 < value <= 100]
    return result[:MAX_CHILDREN]
